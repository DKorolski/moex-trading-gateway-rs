#!/usr/bin/env python3
"""Read-only exact source/tree, generated evidence and installation ZIP verifier."""
import argparse
import json
from pathlib import Path, PurePosixPath
import tempfile
import zipfile

import stage8b_p1f_o2_replay_install as install
from stage8b_p1e_i1a_handoff_safety_check import build_tree_oid, git_object_id
from stage8b_p1f_alor_finam_source_correction_handoff_safety_check import validate_member_name

P = 'installation-evidence/'
REQUIRED = ('snapshot', 'snapshot-final', 'installation-filesystem', 'authority', 'authority-negative',
            'protected-source', 'diff-check', 'exact-elf-smoke')
sha, require = install.sha, install.require


def verify(path):
    with zipfile.ZipFile(path) as z:
        names = z.namelist()
        require(len(names) == len(set(names)) and z.testzip() is None, 'CRC/duplicate entries')
        for i in z.infolist():
            validate_member_name(i.filename)
            require(str(PurePosixPath(i.filename)) == i.filename and i.external_attr >> 16 in (0o100644, 0o100755), 'unsafe member/mode')
        data = {n:z.read(n) for n in names}
        manifest=json.loads(data[P+'source-tree-manifest.json'])
        entries=manifest['entries'];tracked={e['path']:data[e['path']] for e in entries}
        require(len(entries)==len(tracked), 'duplicate source entries')
        for e in entries:
            require(sha(tracked[e['path']])==e['sha256'] and len(tracked[e['path']])==e['size']
                    and z.getinfo(e['path']).external_attr>>16==int(e['mode'],8), 'source bytes/mode')
        tree=build_tree_oid(entries,tracked);raw=data[P+'commit.raw'];ref=git_object_id('commit',raw)
        require(raw.splitlines()[0]==('tree '+tree).encode() and ref==manifest['source_ref'], 'commit/tree')
        index=json.loads(data[P+'generated-index.json'])
        require(set(data)-set(tracked)==set(index)|{P+'generated-index.json'}, 'generated inventory')
        require(all(sha(data[n])==digest for n,digest in index.items()), 'generated bytes')
        marker=dict(line.split('=',1) for line in data['handoff-commit.txt'].decode().splitlines())
        require(marker['source_ref']==ref and marker['source_short_ref']==ref[:7]
                and marker['source_tree']==tree and marker['archive_name']==path.name
                and marker['compiled_ref']==install.SOURCE, 'handoff marker')
    for name in REQUIRED:
        record=json.loads(data[P+name+'.record.json'])
        require(type(record['exit_code']) is int and record['exit_code']==0 and record['timeout'] is False, 'required gate '+name)
        for part in ('stdout','stderr'):
            require(sha(data[P+name+'.'+part])==record[part+'_sha256'], 'capture binding')
    for name in (n for n in data if n.startswith(P) and n.endswith('.record.json')):
        r=json.loads(data[name]);prefix=name.removesuffix('.record.json')
        for part in ('stdout','stderr'):
            require(sha(data[prefix+'.'+part])==r[part+'_sha256'], 'retained diagnostic capture')
    require(b'Ran 12 tests' in data[P+'installation-filesystem.stderr']
            and b'OK' in data[P+'installation-filesystem.stderr']
            and b'23/23' in data[P+'installation-filesystem.stdout']
            and b'10/10' in data[P+'installation-filesystem.stdout'], 'filesystem witnesses')
    require(b'cases=45/45' in data[P+'authority-negative.stdout'], 'authority witnesses')
    snap=json.loads(data[P+'snapshot.stdout'])
    require(snap['status']=='PASS_READ_ONLY' and all(snap[k] is False for k in
            ('mutation_performed','redis_contact','finam_contact','private_bytes_read')), 'snapshot scope')
    require(install.canonical(snap['expected'])==data['installation-replay/before.json'], 'fresh snapshot binding')
    final=json.loads(data[P+'snapshot-final.stdout'])
    require(all(final[k]==v for k,v in snap.items() if k!='observed_at_utc'), 'operational state changed during preparation')
    with tempfile.TemporaryDirectory(prefix='replay-install-check-') as temp:
        root=Path(temp)
        for name,raw in data.items():
            if name.startswith('installation-replay/'):
                p=root/name;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(raw)
        spec,_,old,_=install.validate_prepared(root/'installation-replay')
    for p in install.ELFS:
        require(sha(data[P+'old-elf/'+Path(p).name])==old['payload'][p]['sha256'], 'old fixture ELF')
    scope=json.loads(data[P+'scope.json'])
    require(scope['source_ref']==ref and scope['compiled_ref']==install.SOURCE
            and all(scope[k] is False for k in ('installed','activated','o2_invoked','pushed')), 'package scope')
    require(data[P+'source-vs-accepted.patch']==b'', 'protected source delta')
    accepted=json.loads(data[P+'accepted-artifact/source-tree-manifest.json'])
    accepted_entries=accepted['entries']
    accepted_files={}
    for entry in accepted_entries:
        name=entry['path'];prior=P+'accepted-preimages/'+name
        raw=data[prior] if prior in data else tracked[name]
        require(sha(raw)==entry['sha256'] and len(raw)==entry['size'], 'accepted source bytes')
        accepted_files[name]=raw
        if name.startswith(('crates/','deploy/','.github/')) or name in ('Cargo.toml','Cargo.lock'):
            require(raw==tracked[name], 'protected source drift')
    accepted_tree=build_tree_oid(accepted_entries,accepted_files)
    accepted_commit=data[P+'accepted-artifact/commit.raw']
    require(git_object_id('commit',accepted_commit)==install.SOURCE
            and accepted_commit.splitlines()[0]==('tree '+accepted_tree).encode()
            and ('parent '+install.SOURCE).encode() in data[P+'commit.raw'].splitlines(), 'accepted parent identity')
    build=json.loads(data[P+'accepted-artifact/build.json'])
    require(build['source_ref']==install.SOURCE and build['source_tree']==accepted_tree
            and {b['name']:(b['sha256'],b['size']) for b in build['binaries']}
                == {Path(n).name:v for n,v in install.ELFS.items()}, 'accepted ELF identity')
    review='docs/stage-8/reviews/REVIEW_09dfecb_O2_FIRST_BOOT_REPLAY_ARTIFACT_20261008_RU.txt'
    require(sha(data[review])=='ac27837fa19e3fcf1b64e888cc405951056176155962c59c73b98cb0f40b1f7f',
            'artifact acceptance review')
    require(b'PASS sparse-install ELF inputs network=none activation=false' in data[P+'exact-elf-smoke.stdout'],
            'exact ELF smoke witness')
    for name in ('snapshot','snapshot-final'):
        record=json.loads(data[P+name+'.record.json'])
        require(record['stdin_sha256']==sha(data[P+'drivers/'+name+'-readonly.py']), 'collector source binding')
    require(scope['vps_readonly_contact'] is True and scope['remote_writes'] is False
            and scope['github_ci']=='NOT_RUN', 'operational scope')
    require(json.loads(data['installation-replay/payload/installation-o2-v1.json'])['artifact_sha256']==install.ARTIFACT,
            'accepted artifact lineage')
    native=snap['expected']['host']
    require(native['platform']=='x86_64' and tuple(map(int,native['libc'].split()[1].split('.'))) >= (2,34),
            'native runtime dependencies')
    require(set(native['p0_executables'])==set(install.c.P0_UNITS), 'P0 executable fingerprints')
    return dict(status='PASS',source_ref=ref,source_tree=tree,compiled_ref=install.SOURCE,
                archive_name=path.name,archive_sha256=sha(path.read_bytes()),archive_bytes=path.stat().st_size,
                tracked_members=len(entries),archive_members=len(names),duplicates=0,unsafe_paths=0,symlinks=0,special_files=0,
                new_installation_sha256=spec['new_manifest_sha256'],expected_terminal='FAILED/1/23',
                write_slots=5,filesystem_tests=12,prepared_negatives=23,crash_frontiers=10,authority_negatives=45,
                installed=False,activated=False,o2_invoked=False,vps_readonly_contact=True,remote_writes=False,
                accepted_artifact_sha256=install.ARTIFACT,github_ci='NOT_RUN',o2_status='HOLD')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('archive',type=Path)
    print(json.dumps(verify(p.parse_args().archive),indent=2))
